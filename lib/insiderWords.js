// Lowercase, strip spaces/punctuation, so "ice-cream", "Ice Cream" and "icecream" all match.
function normalizeWord(s) {
  return String(s || "")
    .toLowerCase()
    .normalize("NFC")
    .replace(/[\s\-_.,!?'"“”‘’()]/g, "");
}

